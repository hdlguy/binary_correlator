% a function to produce maximal length (2^N)-1 LFSR sequences

function retval = m_sequence (N)

    poly = uint64(hex2dec([
        "0000000000000001", % 1
        "0000000000000003", % 2
        "0000000000000006", % 3
        "000000000000000c", % 4
        "0000000000000014", % 5
        "0000000000000030", % 6
        "0000000000000060", % 7
        "00000000000000b8", % 8
        "0000000000000110", % 9
        "0000000000000240", % 10
        "0000000000000500", % 11
        "0000000000000829", % 12
        "000000000000100d", % 13
        "0000000000002015", % 14
        "0000000000006000", % 15
        "000000000000d008", % 16
        "0000000000012000", % 17
        "0000000000020400", % 18
        "0000000000040023", % 19
        "0000000000090000", % 20
        "0000000000140000", % 21
        "0000000000300000", % 22
        "0000000000420000", % 23
        "0000000000e10000", % 24
        "0000000001200000", % 25
        "0000000002000023", % 26
        "0000000004000013", % 27
        "0000000009000000", % 28
        "0000000014000000", % 29
        "0000000020000029", % 30
        "0000000048000000", % 31
        "0000000080200003", % 32
        "0000000100080000", % 33
        "0000000204000003", % 34
        "0000000500000000", % 35
        "0000000801000000", % 36
        "000000100000001f", % 37
        "0000002000000031", % 38
        "0000004400000000", % 39
        "000000a000140000", % 40
        "0000012000000000", % 41
        "00000300000c0000", % 42
        "0000063000000000", % 43
        "00000c0000030000", % 44
        "00001b0000000000", % 45
        "0000300003000000", % 46
        "0000420000000000", % 47
        "0000c00000180000", % 48
        "0001008000000000", % 49
        "0003000000c00000", % 50
        "0006000c00000000", % 51
        "0009000000000000", % 52
        "0018003000000000", % 53
        "0030000000030000", % 54
        "0040000040000000", % 55
        "00c0000600000000", % 56
        "0102000000000000", % 57
        "0200004000000000", % 58
        "0600003000000000", % 59
        "0c00000000000000", % 60
        "1800300000000000", % 61
        "3000000000000030", % 62
        "6000000000000000", % 63
        "d800000000000000"  % 64
    ]));

    if N < 1 || N > 64
        error("m_sequence: N must be between 1 and 64");
    endif

    mask = poly(N);
    one  = uint64(1);
    len  = (2^N) - 1;
    seq  = zeros(1, len);

    sr = uint64(1);        % seed must be nonzero WITHIN the low N bits only

    for k = 1:len
        lsb = bitand(sr, one);
        seq(k) = double(lsb);
        sr = bitshift(sr, -1);
        if lsb
            sr = bitxor(sr, mask);
        endif
    endfor

    retval = seq;

endfunction

